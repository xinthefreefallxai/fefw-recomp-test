# Compiles the compute shaders of the GPU ASTC transcode ([gfx] astc_gpu; src/gfx/nvn/nvn_astc_gpu.cpp) with glslang and writes
# src/gfx/nvn/nvn_astc_gpu_shaders.inc (uint32 arrays). The .inc is committed, so building the runtime does not need a shader compiler.
# Sources: src/gfx/nvn/shaders/astc_decode.comp, bc7_encode.comp, bc1_encode.comp.
# Run: python -I scripts/gen_astc_gpu_shaders.py   (exit 1 and no .inc written if a shader fails to compile or validate)
# glslang: the GLSLANG environment variable, else glslang / glslangValidator on PATH (scoop's glslang works). spirv-val (SPIRV_VAL, the Vulkan
# SDK's or PATH) is run when it is found.
import os, shutil, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir = os.path.join(root, "src", "gfx", "nvn", "shaders")
out_path = os.path.join(root, "src", "gfx", "nvn", "nvn_astc_gpu_shaders.inc")

SHADERS = [("kAstcDecodeComp", "astc_decode.comp"), ("kBc7EncodeComp", "bc7_encode.comp"), ("kBc1EncodeComp", "bc1_encode.comp")]

HEADER = """// GENERATED by scripts/gen_astc_gpu_shaders.py from src/gfx/nvn/shaders/{astc_decode,bc7_encode,bc1_encode}.comp: do not edit
// SPIR-V of the GPU ASTC transcode (nvn_astc_gpu.cpp), compiled with glslang -V --target-env vulkan1.1 -Os.
// astc_decode.comp and bc1_encode.comp are adapted from astral-chain-pc-recomp (MIT); see the sources and THIRD_PARTY_NOTICES.md."""


def find_glslang():
    if os.environ.get("GLSLANG"):
        return os.environ["GLSLANG"]
    for name in ("glslang", "glslangValidator"):
        found = shutil.which(name)
        if found:
            return found
    sys.stderr.write("glslang not found (set GLSLANG)\n")
    sys.exit(1)


def find_spirv_val():
    if os.environ.get("SPIRV_VAL"):
        return os.environ["SPIRV_VAL"]
    sdk = os.path.join(r"C:\VulkanSDK\1.4.363.0\Bin", "spirv-val.exe")
    if os.path.exists(sdk):
        return sdk
    return shutil.which("spirv-val")


def compile_one(glslang, spirv_val, tmp, file):
    comp = os.path.join(src_dir, file)
    spv = os.path.join(tmp, file + ".spv")
    res = subprocess.run([glslang, "-V", "--target-env", "vulkan1.1", "-Os", "-o", spv, comp], capture_output=True, text=True)
    if res.returncode != 0:
        sys.stderr.write("glslang failed on %s:\n%s%s" % (file, res.stdout, res.stderr))
        sys.exit(1)
    data = open(spv, "rb").read()
    if len(data) % 4 or len(data) == 0:
        sys.stderr.write("%s: bad SPIR-V size\n" % file)
        sys.exit(1)
    if spirv_val:
        v = subprocess.run([spirv_val, "--target-env", "vulkan1.1", spv], capture_output=True, text=True)
        if v.returncode != 0:
            sys.stderr.write("spirv-val failed on %s:\n%s\n" % (file, v.stdout + v.stderr))
            sys.exit(1)
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def main():
    glslang = find_glslang()
    spirv_val = find_spirv_val()
    with tempfile.TemporaryDirectory() as tmp:
        arrays = [(name, compile_one(glslang, spirv_val, tmp, file)) for name, file in SHADERS]
    lines = [HEADER]
    for name, words in arrays:
        lines.append("static const uint32_t %s[] = {" % name)
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%s)%s" % (out_path, ", ".join("%s %d words" % (n, len(w)) for n, w in arrays),
                                "" if spirv_val else "; spirv-val not found, not validated"))


if __name__ == "__main__":
    main()
